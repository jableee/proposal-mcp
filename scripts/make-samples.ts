// 3. 기존 제안서 — 가상 과거 고객 2곳
function deck(file: string, slides: [string, string[]][]) {
  const p = new pptxgen();
  p.layout = "LAYOUT_WIDE";
  for (const [title, bullets] of slides) {
    const s = p.addSlide();
    s.addText(title, { x: 0.5, y: 0.3, w: 12.3, h: 0.8, fontSize: 26, bold: true, color: "1F3864" });
    s.addText(bullets.map((b) => ({ text: b, options: { bullet: true } })), { x: 0.7, y: 1.4, w: 11.9, h: 5.5, fontSize: 16, valign: "top" });
  }
  return p.writeFile({ fileName: OUT + file });
}

